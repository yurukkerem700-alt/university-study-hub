-- Notora veritabanı şeması (PostgreSQL / Supabase)
-- Canlı veritabanından (notbul projesi) doğrulanmış yapıdır. Kullanıcı kimliği auth.users tablosundadır.

create table public.profiles (
  id uuid primary key references auth.users(id),
  display_name text not null default 'Öğrenci',
  university text, department text,
  study_year smallint check (study_year between 1 and 8),
  role text not null default 'student' check (role in ('student','teacher','admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.user_preferences (
  id uuid primary key references auth.users(id),
  education_level text default 'Lisans',
  university text, department text, study_year smallint, goal text,
  daily_minutes smallint default 60,
  focus_mode text default 'pomodoro',
  theme text default 'system',
  notifications boolean default true,
  preferred_topics text[] default '{}',
  updated_at timestamptz not null default now()
);

create table public.notes (
  id bigint generated by default as identity primary key,
  title text not null, description text,
  department text not null,
  study_year smallint check (study_year between 1 and 8),
  topic text,
  content_type text not null default 'Ders Notu',
  university text, lecturer text,
  file_path text, file_name text, file_size bigint,
  downloads integer not null default 0 check (downloads >= 0),
  likes_count integer not null default 0 check (likes_count >= 0),
  rating numeric not null default 0 check (rating between 0 and 5),
  ratings_count integer not null default 0 check (ratings_count >= 0),
  uploader_id uuid references auth.users(id),
  status text not null default 'published' check (status in ('pending','published','rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.note_likes (
  note_id bigint not null references public.notes(id),
  user_id uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  primary key (note_id, user_id)
);

create table public.bookmarks (
  note_id bigint not null references public.notes(id),
  user_id uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  primary key (note_id, user_id)
);

create table public.note_ratings (
  note_id bigint not null references public.notes(id),
  user_id uuid not null references auth.users(id),
  rating smallint not null check (rating between 1 and 5),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (note_id, user_id)
);

create table public.note_download_events (
  id bigint generated by default as identity primary key,
  note_id bigint not null references public.notes(id),
  user_id uuid references auth.users(id),
  client_token text not null,
  created_at timestamptz not null default now(),
  unique (note_id, client_token)
);

create table public.knowledge_resources (
  id bigint generated by default as identity primary key,
  title text not null, summary text not null, category text not null,
  resource_type text not null default 'web',
  tags text[] not null default '{}',
  source_name text not null, source_url text not null,
  authority text not null default 'official',
  verified_at date not null default current_date,
  last_checked_at timestamptz not null default now(),
  featured boolean not null default false,
  created_at timestamptz not null default now(),
  domain text,
  year_level smallint check (year_level between 1 and 4),
  subject text, topic text
);

create table public.academic_events (
  id bigint generated by default as identity primary key,
  title text not null, organizer text not null,
  event_date timestamptz not null, deadline_date timestamptz,
  category text not null, source_url text not null, source_name text not null,
  created_at timestamptz not null default now()
);

create table public.study_catalog (
  id bigint generated by default as identity primary key,
  domain text not null,
  year_level smallint not null check (year_level between 1 and 4),
  semester smallint check (semester between 1 and 2),
  subject text not null, topic text not null, skill text,
  level text not null default 'temel' check (level in ('temel','orta','ileri')),
  roadmap_type text not null default 'genel' check (roadmap_type in ('genel','alan')),
  created_at timestamptz not null default now()
);

create table public.universities_catalog (
  id bigint generated by default as identity primary key,
  name text not null unique,
  university_type text not null default 'Devlet',
  city text,
  country_region text not null default 'Türkiye',
  source_year smallint not null default 2025,
  source_name text not null default 'YÖK Atlas 2025 tabanlı açık veri'
);

create table public.programs_catalog (
  id bigint generated by default as identity primary key,
  name text not null, level text not null, score_type text, duration_years text,
  faculty_examples text[] not null default '{}',
  source_year smallint not null default 2025,
  source_name text not null default 'YÖK Atlas 2025 tabanlı açık veri',
  unique (name, level, score_type, duration_years)
);

-- Çalışma Defteri (kişiye özel)
create table public.study_notebooks (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 120),
  course text,
  body text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.study_highlights (
  id bigint generated by default as identity primary key,
  notebook_id bigint not null references public.study_notebooks(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  start_pos integer not null check (start_pos >= 0),
  end_pos integer not null,
  color text not null default 'yellow' check (color in ('yellow','green','blue','pink')),
  important boolean not null default false,
  comment text,
  created_at timestamptz not null default now(),
  check (end_pos > start_pos)
);

create table public.study_flashcards (
  id bigint generated by default as identity primary key,
  notebook_id bigint references public.study_notebooks(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  front text not null, back text not null,
  box smallint not null default 1 check (box between 1 and 5),
  next_review date not null default current_date,
  created_at timestamptz not null default now()
);

create index study_notebooks_user_idx on public.study_notebooks(user_id);
create index study_highlights_notebook_idx on public.study_highlights(notebook_id);
create index study_flashcards_user_idx on public.study_flashcards(user_id, next_review);

-- Satır düzeyinde güvenlik (RLS): çalışma defteri yalnızca sahibine açıktır.
alter table public.study_notebooks enable row level security;
alter table public.study_highlights enable row level security;
alter table public.study_flashcards enable row level security;
create policy study_notebooks_own on public.study_notebooks for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy study_highlights_own on public.study_highlights for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy study_flashcards_own on public.study_flashcards for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
grant select, insert, update, delete on public.study_notebooks, public.study_highlights, public.study_flashcards to authenticated;
